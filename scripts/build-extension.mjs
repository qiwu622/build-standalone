import {readFile,writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';

// Deterministic, dependency-free bundle of our own modules. No eval/remote code.
export async function extensionBundle(){
 const parts=[];
 for(const file of ['transport.js','runtime.js','browser-entry.js']){
  const source=(await readFile(new URL('../extensions/build-standalone-adapter/'+file,import.meta.url),'utf8')).replace(/\r\n/g,'\n');
  parts.push(source.replace(/^import .*;\r?\n/gm,'').replace(/^export (?=(?:async )?function |const )/gm,''));
 }
 return '// Generated by npm run build:extension. Edit adapter source modules instead.\n(()=>{\n\'use strict\';\n'+parts.join('\n')+'\nwatchSillyTavernPage();\n})();\n';
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){
 const output=new URL('../extensions/build-browser-bridge/sillytavern-main.js',import.meta.url),expected=await extensionBundle();
 if(process.argv.includes('--check')){
  if((await readFile(output,'utf8')).replace(/\r\n/g,'\n')!==expected)throw new Error('浏览器酒馆分流包未同步，请运行 npm run build:extension');
 }else await writeFile(output,expected);
}
